/** เขตที่ศูนย์นี้รับผิดชอบ — ศูนย์ที่ยังไม่มีในตารางใช้ของศูนย์ตั้งต้น
    (ไม่คืนอาร์เรย์ว่าง ไม่งั้นตัวกรองจะกลายเป็นดรอปดาวน์เปล่า). */
export const getCenterDistricts = (centerId) =>
  CENTER_DISTRICTS[centerId] || CENTER_DISTRICTS[DEFAULT_CLINIC_VALUE];

/** ตัวเลือกของ <FilterDropdown prefix='เขต:'> — "ทุกเขต" หมายถึงทุกเขตของศูนย์นี้ */
export const buildDistrictFilterOptions = (centerId) => ([
  { value: 'all', label: 'ทุกเขต' },
  ...getCenterDistricts(centerId).map((d) => ({ value: d, label: d })),
]);

/** ค่าตัวกรองที่ยังใช้ได้กับศูนย์ปัจจุบัน — เปลี่ยนศูนย์แล้วเขตเดิมที่ไม่ได้อยู่
    ในความรับผิดชอบต้องตกกลับเป็น "ทุกเขต" ไม่ใช่ค้างจนตารางว่าง. */
export const resolveDistrictFilter = (centerId, value) =>
  (value && getCenterDistricts(centerId).includes(value) ? value : 'all');
