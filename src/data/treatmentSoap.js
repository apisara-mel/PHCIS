export const soapCharCount = (soap) =>
  ['s', 'o', 'a', 'p'].reduce((n, k) => n + String(soap?.[k] || '').trim().length, 0);

export const soapHasContent = (soap) =>
  ['s', 'o', 'a', 'p'].some((k) => String(soap?.[k] || '').trim().length >= MIN_SOAP_CHARS);

/* ช่องที่ต่างจาก baseline ที่คัดลอกมา — กัน copy-forward กลายเป็นข้อมูลลวง */
export const soapDiffFields = (soap, baseline) => {
  if (!baseline) return ['s', 'o', 'a', 'p'];
  return ['s', 'o', 'a', 'p'].filter(
    (k) => String(soap?.[k] || '').trim() !== String(baseline?.[k] || '').trim(),
  );
};

