export const pastSoapFor = (hn, excludeVisitId) => PAST_SOAP
  .filter((n) => n.hn === hn && n.visitId !== excludeVisitId)
  .map((n) => ({ ...n }));

let seq = 0;

/* บันทึก SOAP ของ visit นี้ลงคลังประวัติ เพื่อให้ครั้งถัดไป copy-forward ได้ */
export const rememberSoap = ({ hn, visitId, visitDate, clinic, soap }) => {
  const existing = PAST_SOAP.find((n) => n.hn === hn && n.visitId === visitId);
  const payload = {
    hn,
    visitId,
    visitDate: visitDate || stampNow().split(' · ')[0],
    clinic: clinic || 'ตรวจรักษาทั่วไป (OPD)',
    author: CURRENT_CLINICIAN.name,
    s: soap?.s || '', o: soap?.o || '', a: soap?.a || '', p: soap?.p || '',
  };
  if (existing) {
    Object.assign(existing, payload);
  } else {
    seq += 1;
    PAST_SOAP.unshift({ id: `soap-${Date.now().toString(36)}-${seq}`, ...payload });
  }
  emit();
  return payload;
};

