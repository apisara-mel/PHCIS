/** Resolve avatar for a mock doctor name (spacing-tolerant). */
export const resolveDoctorAvatar = (name) => {
  const key = String(name || '').replace(/\s+/g, '');
  const hit = DOCTORS.find((d) => d.name.replace(/\s+/g, '') === key);
  if (hit?.avatar) return hit.avatar;
  if (key.includes('สมชาย')) return '/illustration/mobile/doctor-somchai.png';
  if (key.includes('สมหญิง') || key.includes('รักษาดี') || key.includes('รักษ์ดี')) {
    return '/illustration/mobile/doctor-somying.png';
  }
  if (key.includes('อรอนงค์')) return '/illustration/mobile/doctor-ornanong.png';
  return '/illustration/mobile/doctor-d.png';
};

