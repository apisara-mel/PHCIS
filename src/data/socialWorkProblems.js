/* แผนที่รหัสย่อชุดเดิม (P01–P17 ที่ใช้ในทะเบียน/คิวก่อนมติครั้งที่ 3) →
   รหัส 4 หลักของบัญชีปัญหาทางสังคมฉบับใหม่ เพื่อให้ข้อมูลเดิมยังรายงานรวม
   กับข้อมูลใหม่ได้โดยไม่ต้อง migrate mock ทั้งชุด */
export const SW_LEGACY_PROBLEM_MAP = {
  P01: '1001', P02: '1003', P03: '0802', P04: '1104', P05: '1201',
  P06: '0201', P07: '0709', P08: '1303', P09: '1415', P10: '1307',
  P11: '1404', P12: '1413', P13: '1602', P14: '0102', P15: '0206',
  P16: '1301', P17: '1406',
};

/** รับได้ทั้งรหัสเดิม P0x และรหัสใหม่ 4 หลัก — คืนรหัส 4 หลักเสมอ */
export const toSwProblemCode = (code) => {
  if (!code) return '';
  const s = String(code);
  return SW_LEGACY_PROBLEM_MAP[s] || s;
};

export const findSwProblemCode = (code) => FLAT.find((i) => i.code === toSwProblemCode(code)) || null;

export const swProblemCategoryOf = (code) => {
  const resolved = toSwProblemCode(code);
  return resolved ? String(resolved).slice(0, 2) : '';
};

export const isSwProblemCodeSensitive = (code) => !!findSwProblemCode(code)?.sensitive;

/** ป้ายที่แสดงบนจอ — masked เมื่อเป็นรหัสลับและผู้ใช้ไม่มีสิทธิ §1.4.2 */
export const resolveSwProblemCodeLabel = (code) => {
  const item = findSwProblemCode(code);
  if (!item) return '—';
  if (item.sensitive && !hasSocialWorkRights()) return `${item.code} — ${SW_MASKED}`;
  return `${item.code} — ${item.label}`;
};

/** ป้ายของหมวดหลัก (ไม่ถือเป็นข้อมูลลับ — ใช้ในรายงานระดับกอง/ผู้บริหาร) */
export const resolveSwProblemCategoryLabel = (categoryCode) => {
  const cat = SW_PROBLEM_TREE.find((c) => c.code === categoryCode);
  return cat ? `${cat.code} — ${cat.label}` : '—';
};

