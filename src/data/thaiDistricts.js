/** รายชื่อเขต/อำเภอของจังหวัดที่เลือก — ไม่ได้เลือกจังหวัด = [] (ช่องถูก disable) */
export const districtsOfProvince = (province) => {
  const p = String(province || '').trim();
  if (!p) return [];
  if (p === BANGKOK) return Object.keys(BANGKOK_DISTRICTS);
  if (PROVINCE_DISTRICTS[p]) return PROVINCE_DISTRICTS[p];
  /* จังหวัดที่ยังไม่มีข้อมูลอำเภอ — อย่างน้อยต้องเลือกอำเภอเมืองได้ */
  const known = THAI_PROVINCES.some((x) => x.name === p);
  return known ? [`เมือง${p}`] : [];
};

/** รายชื่อแขวง/ตำบลของเขตที่เลือก — มีเฉพาะ กทม. ตอนนี้ */
export const subdistrictsOfDistrict = (province, district) => {
  const p = String(province || '').trim();
  const d = String(district || '').trim();
  if (!p || !d) return [];
  if (p === BANGKOK) return BANGKOK_DISTRICTS[d] || [];
  return [];
};
