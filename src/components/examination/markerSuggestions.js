const resolveSide = (marker) => {
  const side = marker?.side;
  if (side === 'back') return 'back';
  return 'front';
};

const resolveRegion = (marker) => {
  const side = resolveSide(marker);
  const top = Number(marker?.topPercent ?? 50);
  const regions = SUGGESTION_LIBRARY[side] ?? [];
  return regions.find((r) => top >= r.topRange[0] && top < r.topRange[1])
    ?? regions[regions.length - 1]
    ?? null;
};

export const getMarkerRegionLabel = (marker) => resolveRegion(marker)?.name ?? '';

export const getMarkerSuggestionPool = (marker) => resolveRegion(marker)?.items ?? [];

export const MIN_SUGGEST_QUERY_LENGTH = 3;

export const filterMarkerSuggestions = (marker, query, limit = 6) => {
  const text = String(query ?? '').trim();
  if (text.length < MIN_SUGGEST_QUERY_LENGTH) return [];
  const pool = getMarkerSuggestionPool(marker);
  if (!pool.length) return [];
  const needle = text.toLocaleLowerCase('th');
  const matches = pool.filter((item) => {
    if (item.toLocaleLowerCase('th') === needle) return false;
    return item.toLocaleLowerCase('th').includes(needle);
  });
  return matches.slice(0, limit);
};
