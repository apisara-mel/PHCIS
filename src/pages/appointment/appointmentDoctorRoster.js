const DEFAULT_SLOT_MINUTES = 15;
const DEFAULT_WORK_HOURS = { start: '08:00', end: '16:00' };

/** Build appointment doctor list — defaults to 25 unique rows, no duplicate cycling. */
export function buildDoctorRoster(total = DOCTOR_ROSTER_SIZE) {
  const capped = Math.min(total, DOCTOR_SEEDS.length);
  return DOCTOR_SEEDS.slice(0, capped).map((seed, index) => ({
    id: index + 1,
    slotMinutes: seed.slotMinutes ?? DEFAULT_SLOT_MINUTES,
    workHours: seed.workHours ?? DEFAULT_WORK_HOURS,
    ...seed,
  }));
}

/** Dropdown options for appointment form — all roster doctors. */
export function doctorSelectOptions(doctors = buildDoctorRoster()) {
  return doctors.map((d) => ({ value: d.name, label: d.name }));
}

/** Lookup doctor display name by staff id. */
export function doctorNameById(doctors, staffId) {
  return doctors.find((d) => d.id === staffId)?.name ?? '';
}
